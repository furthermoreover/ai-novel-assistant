    """按指令关键词自动匹配技能"""
    kw_map = {
        "opening": ["开篇", "黄金三章", "第一章", "前三章", "开头"],
        "continuation": ["续写", "接着写", "下一章", "继续写", "后续"],
        "outline": ["大纲", "框架", "剧情规划", "卷纲"],
        "character": ["人物", "人设", "角色", "人物卡", "角色卡", "主角设计"],
        "goldenfinger": ["金手指", "系统", "能力设定", "外挂", "技能设定"],
        "shuangdian": ["爽点", "节奏", "爆点"],
        "foreshadowing": ["伏笔", "悬念", "埋线"],
        "intro": ["简介", "导语", "文案", "宣传语"],
        "dialogue": ["对话", "对白", "台词"],
        "editor": ["诊断", "审稿", "编辑", "评估", "修改意见", "投稿"],
    }
    for sid, kws in kw_map.items():
        for kw in kws:
            if kw in instruction:
                return SKILL_MAP[sid]
    return None
